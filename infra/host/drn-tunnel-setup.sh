#!/bin/bash
# [P12-04] Locally-managed Cloudflare Tunnel without copying a token through the clipboard.
# One-time, after `cloudflared tunnel login` has written ~/drn/cloudflared/cert.pem (Aki clicks
# Authorize for the zone in the browser; the certificate is downloaded by cloudflared itself).
#   drn-tunnel-setup.sh <API_HOST> [public|hooks-only]
# Steps: create tunnel drn-tunnel (credentials JSON written next to the cert), create the DNS
# CNAME <API_HOST> -> <tunnel-id>.cfargotunnel.com, write ~/drn/cloudflared/config.yml.
# Ingress "hooks-only" (default until Cloudflare Access exists): only /hooks/ecpay/* and /health
# reach drn-backend, everything else answers 404 at the edge. "public": whole host (requires the
# Access applications of docs/ops/edge-cloudflare.md to be in place first).
# Files in ~/drn/cloudflared are 600 and never printed; the tunnel id is not a secret.
set -euo pipefail
umask 077
# shellcheck disable=SC1091
. "$HOME/drn/bin/drn-lib.sh"
host="${1:-}"; mode="${2:-hooks-only}"
[ -n "$host" ] || { echo "usage: drn-tunnel-setup.sh <API_HOST> [public|hooks-only]" >&2; exit 2; }
dir="$drn_dir/cloudflared"
[ -f "$dir/cert.pem" ] || { echo "drn-tunnel-setup: $dir/cert.pem missing; run the login first" >&2; exit 1; }
image="$(grep -E '^[[:space:]]+image: cloudflare/cloudflared:' "$drn_dir/docker-compose.prod.yml" | head -n 1 | sed -E 's/^[[:space:]]+image: //')"
[ -n "$image" ] || { echo "drn-tunnel-setup: cloudflared image not found in the compose file" >&2; exit 1; }
cf() { "$drn_docker" run --rm -v "$dir:/home/nonroot/.cloudflared" "$image" "$@"; }

name="drn-tunnel"
if ! cf tunnel list --name "$name" --output json | grep -q '"id"'; then
  cf tunnel create "$name" >/dev/null
fi
id="$(cf tunnel list --name "$name" --output json | sed -nE 's/.*"id": *"([0-9a-f-]+)".*/\1/p' | head -n 1)"
[ -n "$id" ] || { echo "drn-tunnel-setup: could not read the tunnel id" >&2; exit 1; }
[ -f "$dir/$id.json" ] || { echo "drn-tunnel-setup: credentials $id.json missing" >&2; exit 1; }
chmod 600 "$dir"/*.json "$dir/cert.pem"

cf tunnel route dns "$name" "$host" 2>&1 | grep -viE "token|secret" || true

case "$mode" in
  hooks-only) rules='  - hostname: '"$host"'
    path: ^/hooks/ecpay/
    service: http://drn-backend:9000
  - hostname: '"$host"'
    path: ^/health$
    service: http://drn-backend:9000
  - service: http_status:404' ;;
  public) rules='  - hostname: '"$host"'
    service: http://drn-backend:9000
  - service: http_status:404' ;;
  *) echo "drn-tunnel-setup: mode must be public or hooks-only" >&2; exit 2 ;;
esac
cat > "$dir/config.yml" <<CFG
# Generated by drn-tunnel-setup.sh ($mode). Locally-managed tunnel $name.
tunnel: $id
credentials-file: /home/nonroot/.cloudflared/$id.json
no-autoupdate: true
ingress:
$rules
CFG
chmod 600 "$dir/config.yml"
cf tunnel --config /home/nonroot/.cloudflared/config.yml ingress validate
echo "tunnel=$id host=$host mode=$mode"
