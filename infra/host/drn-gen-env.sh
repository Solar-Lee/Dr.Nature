#!/bin/bash
# [P12-17] Generates the production ~/drn/.env on the Mac mini. Run by AKI, never by an agent:
#   bash ~/drn/bin/drn-gen-env.sh <API_HOST>        e.g. drn-api.smilelife.tw (D12)
# DATABASE_URL carries ?sslmode=disable: drn-postgres has no TLS (it is reachable only on drn_net),
# and Medusa 2.21.2's migration lock connection otherwise turns SSL on for every host that is not
# localhost (@medusajs/utils load-module-database-config.js:14-30), so db:migrate timed out.
# Secrets come from openssl rand and are written straight into the file (mode 600); nothing
# secret is ever printed. Refuses to overwrite an existing file. ECPay values are ECPay's PUBLIC
# stage sandbox merchants (the same public values as infra/dev-env.sh); U-02 replaces them by hand.
# Names must stay within docs/ENV.md (scripts/check-env-names.mjs).
set -euo pipefail
umask 077

host="${1:-}"
case "$host" in
  "") echo "usage: drn-gen-env.sh <API_HOST>" >&2; exit 2 ;;
  *localhost*|*127.0.0.1*|*.local) echo "drn-gen-env: <API_HOST> must be the public host name, not $host" >&2; exit 2 ;;
  *.*) ;;
  *) echo "drn-gen-env: <API_HOST> must contain a dot (public host name), got $host" >&2; exit 2 ;;
esac

dir="$HOME/drn"
out="$dir/.env"
if [ -e "$out" ]; then
  echo "drn-gen-env: $out already exists; refusing to overwrite (remove it yourself only before drn-postgres was first started)" >&2
  exit 1
fi
install -d -m 700 "$dir"

pg_password="$(openssl rand -hex 32)"
jwt_secret="$(openssl rand -hex 32)"
cookie_secret="$(openssl rand -hex 32)"

storefront="https://dr.nature.smilelife.tw"
api="https://$host"

tmp="$(mktemp "$dir/.env.XXXXXX")"
cat > "$tmp" <<ENV
# Dr.Nature production environment (Mac mini). Generated by drn-gen-env.sh; never commit, never paste.
POSTGRES_USER=drn
POSTGRES_PASSWORD=$pg_password
POSTGRES_DB=drn
DATABASE_URL=postgres://drn:$pg_password@drn-postgres:5432/drn?sslmode=disable
JWT_SECRET=$jwt_secret
COOKIE_SECRET=$cookie_secret
STORE_CORS=$storefront
ADMIN_CORS=$api
AUTH_CORS=$storefront,$api
MEDUSA_BACKEND_URL=$api
STOREFRONT_URL=$storefront
MEDUSA_DISABLE_TELEMETRY=true
# ECPay PUBLIC stage sandbox (developers.ecpay.com.tw/2856/, /7398/); replaced by hand at U-02.
ECPAY_ENV=stage
ECPAY_MERCHANT_ID=3002607
ECPAY_HASH_KEY=pwFHCqoQZGmho4w6
ECPAY_HASH_IV=EkRm7iFT261dpevs
ECPAY_LOGISTICS_MERCHANT_ID=2000933
ECPAY_LOGISTICS_HASH_KEY=XBERn1YOvpM9nfZc
ECPAY_LOGISTICS_HASH_IV=h1ONHk4P4yqbl5LK
ECPAY_LOGISTICS_CONTRACT=C2C
# Fictional sender for the sandbox (same as infra/dev-env.sh); the real sender comes with U-02/U-13.
ECPAY_LOGISTICS_SENDER_NAME=王小明
ECPAY_LOGISTICS_SENDER_CELLPHONE=0912345678
ENV
chmod 600 "$tmp"
mv "$tmp" "$out"

# Output: permissions/owner and the variable NAMES only.
ls -l "$out" | awk '{print $1, $3}'
grep -E '^[A-Z0-9_]+=' "$out" | cut -d= -f1
